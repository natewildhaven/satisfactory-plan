#!/usr/bin/env python3
"""Build js/recipes.js from SatisfactoryTools' game data dump.

Usage:
  curl -o data.json https://raw.githubusercontent.com/greeny/SatisfactoryTools/dev/data/data.json
  python3 tools/build_recipes.py data.json > js/recipes.js

Rates are stored per minute at 100% clock so the app never has to think
about cycle times.
"""
import json
import sys

# Items that have more than one standard recipe: which one the guide uses.
DEFAULTS = {
    "Fuel": "Fuel",
    "Plastic": "Plastic",
    "Rubber": "Rubber",
    "Aluminum Ingot": "Aluminum Ingot",
    "Ficsite Ingot": "Ficsite Ingot (Aluminum)",
    "Biomass": "Biomass (Leaves)",
}
# Items the solver must never try to craft: they come from nodes, wells or the world.
RAW = [
    "Iron Ore", "Copper Ore", "Limestone", "Coal", "Caterium Ore", "Raw Quartz",
    "Sulfur", "Bauxite", "Uranium", "SAM", "Crude Oil", "Water", "Nitrogen Gas",
    "Leaves", "Wood", "Mycelia",
]
SKIP_PREFIXES = ("Unpackage ",)


def main(path):
    d = json.load(open(path))
    items, buildings = d["items"], d["buildings"]
    machines = {}
    for v in buildings.values():
        meta = v.get("metadata", {})
        if meta.get("manufacturingSpeed"):
            machines[v["name"]] = {
                "power": meta.get("powerConsumption", 0),
                "exp": meta.get("powerConsumptionExponent", 1.321929),
            }
    for name in ("Miner Mk.1", "Miner Mk.2", "Miner Mk.3", "Water Extractor", "Oil Extractor"):
        for v in buildings.values():
            if v["name"] == name:
                meta = v["metadata"]
                machines[name] = {"power": meta["powerConsumption"], "exp": meta["powerConsumptionExponent"]}

    raw_ids = {k for k, v in items.items() if v["name"] in RAW}
    recipes = {}
    for k, v in d["recipes"].items():
        if not v["producedIn"] or v["producedIn"][0] not in buildings:
            continue
        machine = buildings[v["producedIn"][0]]["name"]
        if machine not in machines or v["name"].startswith(SKIP_PREFIXES):
            continue
        # Converter recipes that turn one ore into another are not part of this guide.
        if any(p["item"] in raw_ids for p in v["products"]) and machine == "Converter":
            continue
        per_min = 60.0 / v["time"]
        r = {
            "name": v["name"],
            "machine": machine,
            "alt": bool(v["alternate"] or v["name"].startswith("Alternate:")),
            "in": [[items[i["item"]]["name"], round(i["amount"] * per_min, 6)] for i in v["ingredients"]],
            "out": [[items[i["item"]]["name"], round(i["amount"] * per_min, 6)] for i in v["products"]],
        }
        if v.get("isVariablePower"):
            r["power"] = (v["minPower"] + v["maxPower"]) / 2
        recipes[v["name"]] = r

    # Pick the default recipe for each craftable item.
    default = {}
    for r in recipes.values():
        if r["alt"]:
            continue
        main_out = r["out"][0][0]
        if main_out in RAW and main_out != "Water":
            continue
        if main_out in DEFAULTS:
            if r["name"] == DEFAULTS[main_out]:
                default[main_out] = r["name"]
        elif main_out not in default:
            default[main_out] = r["name"]
    default.pop("Water", None)

    liquids = sorted(v["name"] for v in items.values() if v.get("liquid"))
    used = {p[0] for r in recipes.values() for p in r["in"] + r["out"]}
    stack = {v["name"]: v["stackSize"] for v in items.values() if v["name"] in used and not v.get("liquid")}
    out = {
        "machines": machines,
        "recipes": recipes,
        "defaults": default,
        "raw": RAW,
        "liquids": liquids,
        "stack": stack,
    }
    sys.stdout.write("// Generated by tools/build_recipes.py from Satisfactory 1.x game data. Do not edit by hand.\n")
    sys.stdout.write("window.GAME = " + json.dumps(out, indent=0, sort_keys=True) + ";\n")


if __name__ == "__main__":
    main(sys.argv[1])
